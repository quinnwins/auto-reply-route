    def synthesize_team_review(self, team_type: str, step_output: str) -> TeamReviewVerdict:
        """Aggregates subagent critiques into a structured living-room verdict.

        Identifies code defects, wiring logic flaws, or executive-level compromises.
        """
        team = self.get_team(team_type)
        raw_text = step_output.strip()

        # Check for empty output
        if not raw_text:
            critique = PersonaCritique(
                persona_name="Team Reviewer",
                role="auditor",
                passed=False,
                critique="No implementation output or review artifacts were provided for evaluation.",
                issues=["Empty step output received"],
                recommendations=["Provide the code, test execution logs, or visual evidence to review."],
            )
            return TeamReviewVerdict(
                team_type=team.team_id,
                team_name=team.name,
                passed=False,
                living_room_verdict=(
                    "Nothing was submitted for review yet. The team needs to see the code or "
                    "test results before checking it."
                ),
                critiques=[critique],
                defects=["Missing step output"],
                compromises=[],
            )

        # Run persona-specific audits based on team mandate
        canonical = team.team_id
        if canonical in ("qa_team", "qa_team_2"):
            return self._synthesize_qa_review(team, raw_text)
        elif canonical == "executive_team":
            return self._synthesize_executive_review(team, raw_text)
        elif canonical == "system_integration_team":
            return self._synthesize_integration_review(team, raw_text)
        elif canonical == "visual_proof_team":
            return self._synthesize_visual_review(team, raw_text)
        else:
            return self._synthesize_generic_review(team, raw_text)

