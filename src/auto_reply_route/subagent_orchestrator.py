    def _synthesize_qa_review(self, team: SubagentTeam, text: str) -> TeamReviewVerdict:
        """Synthesizes review for 3-Person QA teams."""
        defects: list[str] = []
        critiques: list[PersonaCritique] = []

        # 1. Edge Case Auditor
        edge_issues: list[str] = []
        match = _QA_EDGE_RE.search(text)
        if match:
            snippet = match.group(0).strip()
            edge_issues.append(f"Edge case flaw: {snippet}")

        if "zero_division" in text.lower() or "division by zero" in text.lower():
            edge_issues.append("Unhandled division by zero hazard")

        passed_edge = len(edge_issues) == 0
        defects.extend(edge_issues)
        critiques.append(
            PersonaCritique(
                persona_name=team.personas[0].name,
                role=team.personas[0].role,
                passed=passed_edge,
                critique=(
                    "Boundary conditions and concurrency constraints passed without defects."
                    if passed_edge
                    else f"Flagged {len(edge_issues)} edge case hazard(s) requiring defensive guards."
                ),
                issues=edge_issues,
                recommendations=["Add explicit boundary guards and timeout controls."] if edge_issues else [],
            )
        )

        # 2. Security Auditor
        sec_issues: list[str] = []
        if _QA_SHELL_TRUE_RE.search(text) and ("shlex" not in text and "safe" not in text.lower()):
            sec_issues.append("Unsanitized shell=True invocation detected")

        if _QA_DYNAMIC_EXEC_RE.search(text):
            sec_issues.append("Unsafe dynamic code execution (eval/exec)")

        if _QA_CREDENTIALS_RE.search(text):
            sec_issues.append("Hardcoded API token or credential pattern discovered")

        sec_match = _QA_SEC_VULN_RE.search(text)
        if sec_match:
            snippet = sec_match.group(0).strip()
            sec_issues.append(f"Security vulnerability: {snippet}")

        passed_sec = len(sec_issues) == 0
        defects.extend(sec_issues)
        critiques.append(
            PersonaCritique(
                persona_name=team.personas[1].name,
                role=team.personas[1].role,
                passed=passed_sec,
                critique=(
                    "Zero security vulnerabilities or secret leaks discovered."
                    if passed_sec
                    else f"Discovered {len(sec_issues)} security hazard(s)."
                ),
                issues=sec_issues,
                recommendations=["Use parameter tokenization and remove hardcoded tokens."] if sec_issues else [],
            )
        )

        # 3. Test Coverage Specialist
        test_issues: list[str] = []
        if _QA_TAUTOLOGICAL_RE.search(text):
            test_issues.append("Tautological assertion (assert True) detected in test suite")

        if _QA_SKIPPED_RE.search(text):
            test_issues.append("Skipped test annotation detected — tests must run green without skipping")

        if _QA_EMPTY_STUB_RE.search(text):
            test_issues.append("Empty test stub (pass/...) detected")

        if _QA_FAILURES_RE.search(text):
            test_issues.append("Test assertion failure recorded in test run")

        passed_test = len(test_issues) == 0
        defects.extend(test_issues)
        critiques.append(
            PersonaCritique(
                persona_name=team.personas[2].name,
                role=team.personas[2].role,
                passed=passed_test,
                critique=(
                    "Test coverage is rigorous with authentic assertions and zero skips."
                    if passed_test
                    else f"Identified {len(test_issues)} test rigor defect(s)."
                ),
                issues=test_issues,
                recommendations=["Replace tautological or skipped assertions with concrete validations."] if test_issues else [],
            )
        )

        overall_passed = len(defects) == 0
        living_room = self._format_living_room_verdict(
            team=team,
            passed=overall_passed,
            defects=defects,
            compromises=[],
            critiques=critiques,
        )

        return TeamReviewVerdict(
            team_type=team.team_id,
            team_name=team.name,
            passed=overall_passed,
            living_room_verdict=living_room,
            critiques=critiques,
            defects=defects,
            compromises=[],
            metadata={"total_defects": len(defects)},
        )

