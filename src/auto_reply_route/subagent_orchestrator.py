    def _format_living_room_verdict(
        self,
        team: SubagentTeam,
        passed: bool,
        defects: list[str],
        compromises: list[str],
        critiques: list[PersonaCritique],
    ) -> str:
        """Enforces the Living-Room Test: clear, warm, zero-plumbing human English."""
        canonical = team.team_id

        if passed:
            if canonical in ("qa_team", "qa_team_2"):
                return "The code is solid. All three QA auditors checked edge cases, security, and tests, and found zero issues."
            elif canonical == "executive_team":
                return "Approved with zero compromises. The design is clean, simple, and ready for customers without any hacks or shortcuts."
            elif canonical == "system_integration_team":
                return "Fully wired and synced. All components connect cleanly with the existing codebase and no regressions were introduced."
            elif canonical == "visual_proof_team":
                return "The user experience looks great. All screens follow our design standards, and the walkthrough verified smooth end-to-end interactions."
            return "Everything looks great. The team verified the work and approved it with zero issues."

        # Rejected cases
        if canonical in ("qa_team", "qa_team_2"):
            first_issue = defects[0] if defects else "quality defect"
            count = len(defects)
            return f"The QA team flagged {count} issue{'s' if count > 1 else ''} that must be fixed before release: {first_issue}."
        elif canonical == "executive_team":
            first_comp = (compromises + defects)[0] if (compromises or defects) else "architectural shortcut"
            return f"The executive team rejected this version because of shortcuts in the code: {first_comp}. These must be cleaned up to meet our quality bar."
        elif canonical == "system_integration_team":
            first_defect = defects[0] if defects else "integration flaw"
            count = len(defects)
            return f"The system review caught {count} integration issue{'s' if count > 1 else ''}: {first_defect}. The connections between components need to be fixed."
        elif canonical == "visual_proof_team":
            first_defect = defects[0] if defects else "visual rough edge"
            count = len(defects)
            return f"The visual check found {count} rough edge{'s' if count > 1 else ''}: {first_defect}. The interface needs to be polished before release."

        first_err = (defects + compromises)[0] if (defects or compromises) else "flaw"
        return f"The team found issues that need to be resolved: {first_err}."

