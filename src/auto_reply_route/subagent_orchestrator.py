"""Subagent Team Orchestrator and Review Synthesis Engine.

Implements multi-persona subagent teams, deterministic review synthesis,
living-room verdict generation, and Stratum 3 screenshot evidence manifests.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
import re
from typing import Any, Optional


@dataclass
class AgentPersona:
    """Specialized subagent persona with bounded evaluation mandate."""

    name: str
    role: str
    focus_areas: list[str]
    system_prompt: str
    evaluation_heuristics: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "role": self.role,
            "focus_areas": list(self.focus_areas),
            "system_prompt": self.system_prompt,
            "evaluation_heuristics": list(self.evaluation_heuristics),
        }


@dataclass
class SubagentTeam:
    """Multi-persona review team deployed for a discrete verification turn."""

    team_id: str
    name: str
    personas: list[AgentPersona]
    mandate: str
    verdict_criteria: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "team_id": self.team_id,
            "name": self.name,
            "personas": [p.to_dict() for p in self.personas],
            "mandate": self.mandate,
            "verdict_criteria": list(self.verdict_criteria),
        }


@dataclass
class PersonaCritique:
    """Individual critique generated by a subagent persona."""

    persona_name: str
    role: str
    passed: bool
    critique: str
    issues: list[str] = field(default_factory=list)
    recommendations: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "persona_name": self.persona_name,
            "role": self.role,
            "passed": self.passed,
            "critique": self.critique,
            "issues": list(self.issues),
            "recommendations": list(self.recommendations),
        }


@dataclass
class TeamReviewVerdict:
    """Aggregated outcome of a multi-persona team review."""

    team_type: str
    team_name: str
    passed: bool
    living_room_verdict: str
    critiques: list[PersonaCritique] = field(default_factory=list)
    defects: list[str] = field(default_factory=list)
    compromises: list[str] = field(default_factory=list)
    metadata: dict[str, Any] = field(default_factory=dict)

    def __bool__(self) -> bool:
        return self.passed

    def to_dict(self) -> dict[str, Any]:
        return {
            "team_type": self.team_type,
            "team_name": self.team_name,
            "passed": self.passed,
            "living_room_verdict": self.living_room_verdict,
            "critiques": [c.to_dict() for c in self.critiques],
            "defects": list(self.defects),
            "compromises": list(self.compromises),
            "metadata": dict(self.metadata),
        }

    def to_markdown(self) -> str:
        """Format verdict into clean, customer-facing Markdown."""
        status_badge = "✅ **VERDICT: APPROVED**" if self.passed else "❌ **VERDICT: REJECTED**"
        lines = [
            f"## {self.team_name} — Review Verdict",
            "",
            status_badge,
            "",
            f"**Summary:** {self.living_room_verdict}",
            "",
        ]

        if self.defects:
            lines.append("### 🐛 Identified Defects")
            for d in self.defects:
                lines.append(f"- {d}")
            lines.append("")

        if self.compromises:
            lines.append("### ⚠️ Architectural Compromises & Debt")
            for c in self.compromises:
                lines.append(f"- {c}")
            lines.append("")

        if self.critiques:
            lines.append("### 👥 Subagent Persona Reports")
            for c in self.critiques:
                badge = "PASS" if c.passed else "FAIL"
                lines.append(f"#### [{badge}] {c.persona_name} ({c.role})")
                lines.append(f"{c.critique}")
                if c.issues:
                    lines.append("Issues noted:")
                    for issue in c.issues:
                        lines.append(f"  - {issue}")
                if c.recommendations:
                    lines.append("Recommendations:")
                    for rec in c.recommendations:
                        lines.append(f"  - {rec}")
                lines.append("")

        return "\n".join(lines).strip()


