    def list_teams(self) -> list[str]:
        """Return list of canonical team IDs."""
        return list(self._teams.keys())

    def get_team(self, team_type: str) -> SubagentTeam:
        """Resolve team instance by canonical ID or alias."""
        clean = re.sub(r"[^a-zA-Z0-9_]+", "_", team_type.strip().lower()).strip("_")
        canonical_id = self._aliases.get(clean, clean)
        if canonical_id not in self._teams:
            available = ", ".join(self._teams.keys())
            raise KeyError(f"Unknown team type '{team_type}'. Available teams: {available}")
        return self._teams[canonical_id]

    def build_team_prompt(self, team_type: str, context: str) -> str:
        """Generate structured multi-persona dispatch prompt."""
        team = self.get_team(team_type)
        lines = [
            f"# Multi-Persona Subagent Dispatch: {team.name}",
            "",
            f"**Mandate:** {team.mandate}",
            "",
            "## Personas & Verification Directives",
        ]
        for p in team.personas:
            lines.append(f"### Persona: {p.name} ({p.role})")
            lines.append(f"- **Focus Areas:** {', '.join(p.focus_areas)}")
            lines.append(f"- **System Directive:** {p.system_prompt}")
            lines.append("")

        lines.extend([
            "## Target Context / Implementation Under Review",
            "```",
            context.strip(),
            "```",
            "",
            "Conduct your adversarial audit. For each persona, report:",
            "- Status: PASS | FAIL",
            "- Specific issues or compromises identified",
            "- Concrete recommendations or required fixes",
        ])
        return "\n".join(lines)

