    def generate_screenshot_evidence_manifest(
        self,
        image_paths: list[str],
        walkthrough_summary: str,
        step_index: int = 6,
        feature_name: str = "Feature Implementation",
        passed: bool = True,
        defects: Optional[list[str]] = None,
    ) -> str:
        """Formats visual screenshot proof into a Stratum 3 Milestone Card.

        Anchors visual proof in a compact, typed Markdown receipt (~200-300 tokens)
        preserving context hygiene without carrying raw image tokens across turns.
        """
        clean_paths = [str(p).strip() for p in image_paths if str(p).strip()]

        # Format image gallery
        if clean_paths:
            gallery_lines: list[str] = []
            for idx, p in enumerate(clean_paths, 1):
                p_obj = Path(p)
                label = f"Screenshot {idx}: {p_obj.stem.replace('_', ' ').title()}"
                gallery_lines.append(f"- **{label}** (`{p}`)")
                gallery_lines.append(f"  ![{label}]({p})")
            gallery_block = "\n".join(gallery_lines)
        else:
            gallery_block = "*No visual screenshot images were attached to this turn.*"

        clean_summary = walkthrough_summary.strip() or "*Visual verification completed successfully.*"

        defect_blob = " ".join(defects).lower() if defects else ""
        def has_defect(*keywords: str) -> bool:
            return any(k in defect_blob for k in keywords)

        check = "[x]" if passed else "[ ]"
        check_radii = "[ ]" if has_defect("radi") else check
        check_rhythm = "[ ]" if has_defect("rhythm", "grid") else check
        check_touch = "[ ]" if has_defect("touch", "44") else check
        check_contrast = "[ ]" if has_defect("contrast", "leading") else check
        check_state = "[ ]" if has_defect("state", "hover") else check

        return (
            f"## 📍 Visual Proof Milestone Manifest — Step {step_index}: {feature_name}\n\n"
            f"- **Stratum:** Stratum 3 (Structured Milestone Manifest)\n"
            f"- **Step Index:** {step_index}\n"
            f"- **Artifact Type:** Visual Proof & Simulator Walkthrough\n"
            f"- **Screenshots Verified:** {len(clean_paths)}\n\n"
            f"### 🖼️ Screenshot Evidence Gallery\n"
            f"{gallery_block}\n\n"
            f"### 🔍 Optical & Ergonomic Craft Audit (6-Lens Standard)\n"
            f"- {check_radii} **Concentric Radii:** Inner corners match $R_{{inner}} = \\max(0, R_{{outer}} - P)$\n"
            f"- {check_rhythm} **Strict 4/8pt Rhythm:** Zero arbitrary off-grid pixel margins or paddings\n"
            f"- {check_touch} **Touch Ergonomics:** All interactive hitboxes meet minimum 44x44px target\n"
            f"- {check_contrast} **Contrast & Typography:** Crisp text contrast and balanced headline leading\n"
            f"- {check_state} **State Completeness:** Default, hover, active, and loading states verified\n\n"
            f"### 🚶 User Walkthrough Summary\n"
            f"{clean_summary}\n\n"
            f"---\n"
            f"*Context Ledger Anchor: Compact persistent milestone handoff for visual verification.*"
        )

    def evaluate_step(
        self,
        step_idx: int,
        step_output: str,
        image_paths: Optional[list[str]] = None,
    ) -> TeamReviewVerdict:
        """Convenience method to evaluate any of the 6 canonical workflow steps."""
        # Step 0 / 1: Initial Prompt -> Code feature (QA Team 1 review)
        # Step 2: Auto reply 1 -> QA Team 1
        # Step 3: Auto reply 2 -> QA Team 2
        # Step 4: Auto reply 3 -> Executive Review Team
        # Step 5: Auto reply 4 -> System Integration Team
        # Step 6: Auto reply 5 & 6 -> Visual Proof Team
        step_mapping = {
            0: "qa_team",
            1: "qa_team",
            2: "qa_team_2",
            3: "executive_team",
            4: "system_integration_team",
            5: "visual_proof_team",
            6: "visual_proof_team",
        }
        team_id = step_mapping.get(step_idx, "qa_team")
        verdict = self.synthesize_team_review(team_id, step_output)

        if team_id == "visual_proof_team" and image_paths:
            manifest = self.generate_screenshot_evidence_manifest(
                image_paths=image_paths,
                walkthrough_summary=step_output,
                step_index=step_idx + 1 if step_idx < 6 else 6,
                passed=verdict.passed,
                defects=verdict.defects,
            )
            verdict.metadata["milestone_card"] = manifest

        return verdict
